/** Следующая фраза для чата: идём по перемешанному кругу, пока не покажем всё. */
export function jokeFor(seq: number, salt: number): Joke {
  const n = JOKES.length;
  // Шаг, взаимно простой с длиной списка, даёт перестановку без повторов на круге
  const steps = [7, 11, 13, 17, 19, 23, 29, 31].filter((x) => gcd(x, n) === 1);
  const step = steps[Math.abs(salt) % steps.length] ?? 1;
  return JOKES[(Math.abs(salt) + seq * step) % n];
}

function gcd(a: number, b: number): number {
  return b ? gcd(b, a % b) : a;
}

export function jokeText(j: Joke): string {
  const by = j.by ? `\n\n<i>${j.by}</i>` : '';
  return `<b>${KIND_TITLE[j.kind]}</b>\n\n${j.kind === 'quote' ? `«${j.text}»` : j.text}${by}`;
}
